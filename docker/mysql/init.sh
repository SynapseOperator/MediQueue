#!/usr/bin/env bash
set -euo pipefail

# Passwords are generated as hex by setup-local.php; validate before SQL interpolation.
for password in "$MEDIQUEUE_APP_PASSWORD" "$MEDIQUEUE_MIGRATOR_PASSWORD" "$MEDIQUEUE_TEST_PASSWORD"; do
    if [[ ! "$password" =~ ^[a-f0-9]{48}$ ]]; then
        echo 'Use the 48-character hexadecimal passwords generated by setup-local.php.' >&2
        exit 1
    fi
done

MYSQL_PWD="$MYSQL_ROOT_PASSWORD" mysql --host="${MYSQL_HOST:-localhost}" --port="${MYSQL_PORT:-3306}" --user=root <<SQL
CREATE DATABASE IF NOT EXISTS mediqueue CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE DATABASE IF NOT EXISTS mediqueue_test CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE USER IF NOT EXISTS 'mediqueue_app'@'%' IDENTIFIED BY '$MEDIQUEUE_APP_PASSWORD';
CREATE USER IF NOT EXISTS 'mediqueue_migrator'@'%' IDENTIFIED BY '$MEDIQUEUE_MIGRATOR_PASSWORD';
CREATE USER IF NOT EXISTS 'mediqueue_test'@'%' IDENTIFIED BY '$MEDIQUEUE_TEST_PASSWORD';
GRANT SELECT, INSERT, UPDATE, DELETE ON mediqueue.* TO 'mediqueue_app'@'%';
GRANT ALL PRIVILEGES ON mediqueue.* TO 'mediqueue_migrator'@'%';
GRANT ALL PRIVILEGES ON mediqueue_test.* TO 'mediqueue_test'@'%';
SQL
